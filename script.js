drawThreeBtn.addEventListener('click', async () => {
  // Проверяем единый дневной лимит
  if (apiUrl) {
    const result = await useCardApi('three');
    if (result !== null && !result.allowed) {
      _serverStatus.limit_reached = true;
      modeSelection.classList.add('hidden');
      limitMessage.classList.remove('hidden');
      _startCountdown();
      return;
    }
    if (result === null) {
      if (!checkLimit()) {
        alert("Энергия на сегодня иссякла 🌙 Приходите завтра!"); return;
      }
      incrementLocalUsage();
    }
  } else {
    if (!checkLimit()) {
      alert("Энергия на сегодня иссякла 🌙 Приходите завтра!"); return;
    }
    incrementLocalUsage();
  }

  drawThreeBtn.style.display = 'none';

  // Выбираем 3 уникальных карты
  const deckCopy = [...tarotDeck];
  const picked   = [];
  for (let i = 0; i < 3; i++) {
    const idx = Math.floor(Math.random() * deckCopy.length);
    picked.push(deckCopy.splice(idx, 1)[0]);
  }

  // Всегда используем поле meaning (категорий нет)
  const texts = picked.map(c => c.meaning);

  // Последовательно открываем карты
  picked.forEach((card, index) => {
    setTimeout(() => {
      const cardEl = document.getElementById(`tc-${index}`);
      if (!cardEl) return;
      buildCardFace(card, cardEl);
      cardEl.classList.add('flipped');

      if (window.Telegram?.WebApp?.HapticFeedback) {
        window.Telegram.WebApp.HapticFeedback.impactOccurred('medium');
      }

      // После открытия последней карты — показываем результат
      if (index === 2) {
        setTimeout(() => {
          const totalWords = texts.join(' ').split(/\s+/).filter(Boolean).length;
          const delayMs    = totalWords * 100;  // множитель 100 мс/слово

          document.getElementById('t-meaning-0').innerHTML = `<strong>🔮 Считываю линии прошлого...</strong>`;
          document.getElementById('t-meaning-1').innerHTML = `<strong>🔮 Анализирую вибрации настоящего...</strong>`;
          document.getElementById('t-meaning-2').innerHTML = `<strong>🔮 Выстраиваю вероятности будущего...</strong>`;
          threeResultSection.classList.remove('hidden');
          window.scrollTo({ top: document.body.scrollHeight, behavior: 'smooth' });

          setTimeout(() => {
            document.getElementById('t-meaning-0').innerHTML =
              `<strong>Прошлое — ${picked[0].name}:</strong><br>${texts[0]}`;
            document.getElementById('t-meaning-1').innerHTML =
              `<strong>Настоящее — ${picked[1].name}:</strong><br>${texts[1]}`;
            document.getElementById('t-meaning-2').innerHTML =
              `<strong>Будущее — ${picked[2].name}:</strong><br>${texts[2]}<br><br><em>${picked[2].tip}</em>`;
            window.scrollTo({ top: document.body.scrollHeight, behavior: 'smooth' });
            // Сохраняем сводный расклад в историю
            const threeNames = picked.map(c => c.name).join(' · ');
            const threeMeaning = texts.join('\n\n');
            saveReading(threeNames, threeMeaning, 'three');
          }, delayMs);
        }, 1000);
      }
    }, index * 900);
  });
});
