let _countdownInterval = null;

/** Возвращает миллисекунды до следующей полуночи МСК (UTC+3). */
function _mskMidnightMs() {
  const utcNow    = Date.now();
  const mskOffset = 3 * 3600000;
  const mskNow    = utcNow + mskOffset;
  const mskMidnight = Math.ceil(mskNow / 86400000) * 86400000;
  return mskMidnight - mskOffset - utcNow; // мс до МСК-полуночи
}

function _startCountdown() {
  const timerEl = document.getElementById('countdown-timer');
  if (!timerEl) return;
  if (_countdownInterval) clearInterval(_countdownInterval);

  function _tick() {
    const ms = _mskMidnightMs();
    if (ms <= 0) { clearInterval(_countdownInterval); location.reload(); return; }
    const h = Math.floor(ms / 3600000);
    const m = Math.floor((ms % 3600000) / 60000);
    const s = Math.floor((ms % 60000)   / 1000);
    timerEl.textContent =
      String(h).padStart(2,'0') + ':' +
      String(m).padStart(2,'0') + ':' +
      String(s).padStart(2,'0');
  }
  _tick();
  _countdownInterval = setInterval(_tick, 1000);
}

function _stopCountdown() {
  if (_countdownInterval) { clearInterval(_countdownInterval); _countdownInterval = null; }
  const el = document.getElementById('countdown-timer');
  if (el) el.textContent = '—';
}

